#!/usr/bin/env python3
"""Generate the factory presets: lv2/presets.ttl and lv2/manifest.ttl.
Each preset sets every control port and every pattern step (missing values would keep old ones)."""
import os

URI = "urn:generativearp:arp"
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")

PORT_DEFAULTS = [("rate", 3), ("gate", 50), ("order", 0), ("octaves", 1), ("latch", 0),
                 ("len_prob", 16), ("len_shift", 16), ("len_vel", 16), ("len_gate", 16),
                 ("key", 0), ("scale", 0), ("mut_notes", 0), ("loop_len", 8), ("mut_steps", 0), ("reset", 0),
                 ("transpose", 0), ("rpt", 1), ("rpt_mode", 0)]
STEP_DEFAULTS = {"prob": 100, "shift": 0, "vel": 100, "gate": 0}   # gate: 0 Global, 5..100 %, 101 Tie
G, TIE = 0, 101

# value lists are repeated to 16 steps
PRESETS = [
    ("init", "Init", {}, {}),
    ("accent_bass", "Accent Bass",
     {"gate": 40},
     {"vel":   [130, 70, 90, 70, 120, 70, 90, 60, 130, 70, 90, 70, 120, 80, 100, 70],
      "prob":  [100, 100, 80, 100, 100, 60, 100, 100, 100, 100, 100, 100, 100, 50, 100, 80],
      "shift": [0, 0, 12, 0, 0, 0, -12, 0, 0, 12, 0, 0, 0, 0, 7, 12],
      "gate":  [60, 25, 25, TIE, G, 25, G, 25, 60, 25, TIE, TIE, G, 25, G, 25]}),
    ("polyrhythm", "Polyrhythm 7-3-4-5",
     {"order": 2, "octaves": 2, "len_prob": 7, "len_shift": 3, "len_vel": 4, "len_gate": 5},
     {"prob":  [100, 100, 70, 100, 100, 50, 100] + [100] * 9,
      "shift": [0, 12, 7] + [0] * 13,
      "vel":   [130, 80, 100, 80],
      "gate":  [70, 20, 40, 20, TIE] + [G] * 11}),
    ("turing_minor", "Turing A minor",
     {"gate": 60, "order": 6, "octaves": 2, "key": 9, "scale": 2, "mut_notes": 10, "loop_len": 8},
     {"vel": [120, 80, 100, 80]}),
    ("breathing", "Breathing C major",
     {"rate": 1, "gate": 60, "octaves": 2, "scale": 1, "len_prob": 8, "len_shift": 8, "len_vel": 8, "len_gate": 8,
      "mut_steps": 25},
     {"shift": [0, 0, 2, 0, 4, 0, -3, 0],
      "vel":   [110, 70, 90, 70, 100, 70, 90, 60],
      "prob":  [100, 100, 100, 80, 100, 100, 100, 80]}),
    ("scale_runs", "Scale Runs D dorian",
     {"gate": 70, "octaves": 2, "key": 2, "scale": 3, "rpt": 6, "rpt_mode": 1, "len_vel": 3, "len_gate": 5},
     {"vel":  [125, 80, 95],
      "gate": [G, G, G, G, TIE]}),
]


def steps(name, given):
    vals = given.get(name, [STEP_DEFAULTS[name]])
    return [vals[i % len(vals)] for i in range(16)]


def preset_ttl(pid, label, ports, stepvals):
    out = ["<%s#preset_%s>" % (URI, pid), "    a pset:Preset ;", "    lv2:appliesTo <%s> ;" % URI,
           '    rdfs:label "%s" ;' % label, "    pset:bank <%s#bank_factory> ;" % URI, "    lv2:port"]
    plines = []
    for sym, dflt in PORT_DEFAULTS:
        plines.append('        [ lv2:symbol "%s" ; pset:value %.1f ]' % (sym, float(ports.get(sym, dflt))))
    out.append(" ,\n".join(plines) + " ;")
    out.append("    state:state [")
    cols = {k: steps(k, stepvals) for k in STEP_DEFAULTS}
    slines = []
    for i in range(16):
        slines.append("        " + " ; ".join("<%s#%s%d> %d" % (URI, k, i + 1, cols[k][i]) for k in STEP_DEFAULTS))
    out.append(" ;\n".join(slines))
    out.append("    ] .\n")
    return "\n".join(out)


HEAD = """@prefix lv2:   <http://lv2plug.in/ns/lv2core#> .
@prefix pset:  <http://lv2plug.in/ns/ext/presets#> .
@prefix rdfs:  <http://www.w3.org/2000/01/rdf-schema#> .
@prefix state: <http://lv2plug.in/ns/ext/state#> .
"""

with open(os.path.join(ROOT, "lv2", "presets.ttl"), "w") as f:
    f.write("# Generated by scripts/gen_presets.py - edit the script, not this file.\n" + HEAD + "\n")
    for p in PRESETS:
        f.write(preset_ttl(*p) + "\n")

with open(os.path.join(ROOT, "lv2", "manifest.ttl"), "w") as f:
    f.write("# Generated by scripts/gen_presets.py - edit the script, not this file.\n" + HEAD + "\n")
    f.write("<%s>\n    a lv2:Plugin ;\n    lv2:binary <generative_arp.so> ;\n    rdfs:seeAlso <generative_arp.ttl> .\n\n" % URI)
    f.write('<%s#bank_factory>\n    a pset:Bank ;\n    lv2:appliesTo <%s> ;\n    rdfs:label "Factory" .\n\n' % (URI, URI))
    for pid, label, _, _ in PRESETS:
        f.write("<%s#preset_%s>\n    a pset:Preset ;\n    lv2:appliesTo <%s> ;\n    rdfs:label \"%s\" ;\n"
                "    rdfs:seeAlso <presets.ttl> .\n\n" % (URI, pid, URI, label))
print("Wrote lv2/presets.ttl and lv2/manifest.ttl (%d presets)" % len(PRESETS))
